const categoryMapping = {
  'plage': 'plage',
  'food': 'food',
  'gaming': 'gaming',
  'bar': 'bar',
  'cinema': 'cinema',
  'concert': 'concert',
  'culture': 'culture',
  'rooftop': 'rooftop'
};

async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('MongoDB connected');

    const mappedVenues = venuesData.map(v => {
      const mainCategory = v.categories[0];
      const mappedCategory = categoryMapping[mainCategory] || 'culture';
      const price = budgetTierToPrice[v.budget_tier] || { min: null, max: null, average: null };

      return {
        name: v.name,
        description: v.description,
        category: mappedCategory,
        categories: v.categories.map(c => categoryMapping[c] || c).filter(c => c !== mappedCategory),
        latitude: v.latitude,
        longitude: v.longitude,
        address: v.address,
        city: v.city,
        phone: v.phone,
        rating: v.rating || 0,
        reviewCount: Math.floor(Math.random() * 100) + 10,
        priceRange: {
          min: price.min,
          max: price.max,
          average: price.average,
          unit: 'per_person'
        },
        media: v.image ? [{ url: v.image, type: 'image', isPrimary: true }] : [],
        status: 'verified',
        verificationStatus: 'source_backed',
        sourceTier: 'tourism_official',
        isActive: true,
        tags: v.categories
      };
    });

    await Venue.deleteMany({});
    console.log('Cleared existing venues');

    const result = await Venue.insertMany(mappedVenues);
    console.log(`Inserted ${result.length} venues`);

    console.log('\n=== Summary ===');
    const byCity = {};
    result.forEach(v => {
      byCity[v.city] = (byCity[v.city] || 0) + 1;
    });
    Object.entries(byCity).forEach(([city, count]) => {
      console.log(`${city}: ${count} venues`);
    });

    console.log('\nSeed completed successfully');
    process.exit(0);
  } catch (error) {
    console.error('Seed error:', error);
    process.exit(1);
  }
}

seed();
